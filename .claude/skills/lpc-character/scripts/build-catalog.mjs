#!/usr/bin/env node
/**
 * build-catalog.mjs — regenerate ../catalog.json from a checkout of the
 * Universal LPC Spritesheet Character Generator.
 *
 * The catalog is the "preloaded options" the lpc-character skill quizzes against:
 * which body types, heads, hair, clothes, weapons, … exist, plus the palette
 * colour vocabulary per material. It is derived from the repo's source of truth
 * (sheet_definitions/ + palette_definitions/), NOT scraped from the live site.
 *
 * Usage:
 *   node build-catalog.mjs [lpcCheckoutDir] [outFile]
 *
 * Get a cheap checkout (no big PNGs) with:
 *   git clone --no-checkout --depth 1 --filter=tree:0 \
 *     https://github.com/LiberatedPixelCup/Universal-LPC-Spritesheet-Character-Generator.git /tmp/lpc
 *   cd /tmp/lpc && git sparse-checkout set --no-cone sheet_definitions palette_definitions && git checkout
 *
 * Hash grammar this catalog feeds (see ../reference.md):
 *   <type_name>=<Name with spaces→_>[_<colorOrVariant>]
 *   e.g. head=Zombie_bright_green   body=Body_Color_light   clothes=Robe_blue
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const checkout = resolve(process.argv[2] ?? '/tmp/lpc-defs');
const outFile = resolve(process.argv[3] ?? join(__dirname, '..', 'catalog.json'));

// Body-type / build keys, as used in layer_N maps and the `sex=` hash param.
const BODY_TYPES = ['male', 'female', 'muscular', 'teen', 'pregnant', 'child'];
// Palette material folders under palette_definitions/.
const MATERIALS = ['body', 'cloth', 'hair', 'eye', 'metal', 'all'];

function walkJson(dir) {
    const out = [];
    for (const entry of readdirSync(dir)) {
        const p = join(dir, entry);
        if (statSync(p).isDirectory()) out.push(...walkJson(p));
        else if (entry.endsWith('.json') && !entry.startsWith('meta_')) out.push(p);
    }
    return out;
}

function readJson(p) {
    return JSON.parse(readFileSync(p, 'utf8'));
}

// --- palette colour vocabulary: union of ramp names per material -------------
const colorsByMaterial = {};
for (const material of MATERIALS) {
    const dir = join(checkout, 'palette_definitions', material);
    let files;
    try {
        files = readdirSync(dir).filter((f) => f.endsWith('.json') && !f.startsWith('meta_'));
    } catch {
        continue;
    }
    const colors = new Set();
    for (const f of files) {
        const data = readJson(join(dir, f));
        // A palette file is { colorName: [hex, …], … }.
        for (const key of Object.keys(data)) colors.add(key);
    }
    colorsByMaterial[material] = [...colors].sort();
}

// --- items grouped by type_name ---------------------------------------------
const types = {};
const defFiles = walkJson(join(checkout, 'sheet_definitions'));

for (const file of defFiles) {
    const d = readJson(file);
    const typeName = d.type_name;
    if (!typeName || !d.name) continue;

    // Body types this item ships art for (keys of any layer_N map).
    const bodyTypes = new Set();
    for (let n = 1; n < 10; n++) {
        const layer = d[`layer_${n}`];
        if (!layer || typeof layer !== 'object') continue;
        for (const key of Object.keys(layer)) {
            if (BODY_TYPES.includes(key)) bodyTypes.add(key);
        }
    }

    const item = { name: d.name };
    if (Array.isArray(d.tags) && d.tags.length) item.tags = d.tags;
    if (bodyTypes.size) item.bodyTypes = [...bodyTypes].sort();

    // Colours: an explicit `variants` list, or a palette `recolors` material.
    if (Array.isArray(d.variants) && d.variants.length) {
        item.variants = d.variants; // selectable colour/style names, used verbatim
    } else if (d.recolors && typeof d.recolors === 'object' && !Array.isArray(d.recolors)) {
        if (typeof d.recolors.material === 'string') item.recolor = d.recolors.material;
        // else: palette without a material we can resolve → leave colourless.
    }
    // Otherwise the item has a single fixed appearance (name-only in the hash).

    (types[typeName] ??= { count: 0, items: [] }).items.push(item);
}

for (const t of Object.values(types)) {
    t.items.sort((a, b) => a.name.localeCompare(b.name));
    t.count = t.items.length;
}

const catalog = {
    meta: {
        source: 'LiberatedPixelCup/Universal-LPC-Spritesheet-Character-Generator',
        note: 'Generated by build-catalog.mjs. Hash value = <type_name>=<Name with spaces→_>[_<colorOrVariant>]. Name-only is always a safe match (default colour); a wrong colour drops the item. See ../reference.md.',
        baseUrl: 'https://liberatedpixelcup.github.io/Universal-LPC-Spritesheet-Character-Generator/',
        typeCount: Object.keys(types).length,
        itemCount: defFiles.length,
    },
    // `sex=` hash param picks the build.
    bodyTypes: BODY_TYPES,
    // For a recolour item, available colours = colorsByMaterial[item.recolor].
    // For a variant item, available colours = item.variants.
    colorsByMaterial,
    types: Object.fromEntries(Object.entries(types).sort(([a], [b]) => a.localeCompare(b))),
};

writeFileSync(outFile, JSON.stringify(catalog, null, 2) + '\n');
console.log(
    `Wrote ${outFile}\n  ${catalog.meta.typeCount} types, ${catalog.meta.itemCount} item defs\n  materials: ${Object.entries(
        colorsByMaterial,
    )
        .map(([m, c]) => `${m}(${c.length})`)
        .join(', ')}`,
);
